<?php
/**
 * Database Backup Generation Handler (Administrator Tier)
 * Student Information System (SIS)
 * Constitution v2.0.0 Compliant - Native Procedural PHP
 */

require_once __DIR__ . '/../../config/system.php';
require_once __DIR__ . '/../../config/database.php';
require_once __DIR__ . '/../../includes/session.php';
require_once __DIR__ . '/../../includes/auth.php';
require_once __DIR__ . '/../../includes/functions.php';
require_once __DIR__ . '/../../includes/logger.php';

require_role('Administrator');

if ($_SERVER['REQUEST_METHOD'] !== 'POST') {
    set_flash_message('danger', 'Invalid request method.');
    redirect(APP_URL . '/admin/backup/index.php');
}

// Verify CSRF Token
$csrf_token = $_POST['csrf_token'] ?? '';
if (!verify_csrf_token($csrf_token)) {
    set_flash_message('danger', 'Session security token expired or invalid.');
    redirect(APP_URL . '/admin/backup/index.php');
}

$conn = db_connect();
$user = current_user();

// Ensure backup destination directory exists
$backup_dir = BACKUP_PATH;
if (!is_dir($backup_dir)) {
    mkdir($backup_dir, 0755, true);
}

// List of tables in dependency order
$tables = [
    'roles',
    'programs',
    'academic_years',
    'semesters',
    'users',
    'students',
    'enrollments',
    'system_logs',
    'backup_logs'
];

$timestamp = date('Ymd_His');
$filename = "sis_backup_{$timestamp}.sql";
$filepath = $backup_dir . '/' . $filename;

$handle = fopen($filepath, 'w');
if (!$handle) {
    set_flash_message('danger', 'Unable to create backup file on the server. Please check filesystem write permissions.');
    redirect(APP_URL . '/admin/backup/index.php');
}

// Header preamble
fwrite($handle, "-- ==========================================================\n");
fwrite($handle, "-- Student Information System (SIS) - Database Backup\n");
fwrite($handle, "-- Generated: " . date('Y-m-d H:i:s') . "\n");
fwrite($handle, "-- Generated By: " . $user['username'] . " (" . $user['role_name'] . ")\n");
fwrite($handle, "-- System Version: " . APP_VERSION . "\n");
fwrite($handle, "-- ==========================================================\n\n");
fwrite($handle, "SET NAMES utf8mb4;\n");
fwrite($handle, "SET FOREIGN_KEY_CHECKS = 0;\n\n");

$total_records = 0;

foreach ($tables as $table) {
    // Check if table exists
    $table_check = mysqli_query($conn, "SHOW TABLES LIKE '" . mysqli_real_escape_string($conn, $table) . "'");
    if (mysqli_num_rows($table_check) === 0) {
        continue;
    }

    fwrite($handle, "-- ----------------------------------------------------------\n");
    fwrite($handle, "-- Table structure for `{$table}`\n");
    fwrite($handle, "-- ----------------------------------------------------------\n");
    fwrite($handle, "DROP TABLE IF EXISTS `{$table}`;\n");

    $create_res = mysqli_query($conn, "SHOW CREATE TABLE `{$table}`");
    $create_row = mysqli_fetch_row($create_res);
    fwrite($handle, $create_row[1] . ";\n\n");

    // Table data dump
    fwrite($handle, "-- Dumping data for table `{$table}`\n");
    $data_res = mysqli_query($conn, "SELECT * FROM `{$table}`");
    $table_records = mysqli_num_rows($data_res);
    $total_records += $table_records;

    if ($table_records > 0) {
        while ($row = mysqli_fetch_assoc($data_res)) {
            $escaped_values = [];
            foreach ($row as $field => $val) {
                if ($val === null) {
                    $escaped_values[] = "NULL";
                } else {
                    $escaped_values[] = "'" . mysqli_real_escape_string($conn, $val) . "'";
                }
            }
            fwrite($handle, "INSERT INTO `{$table}` VALUES (" . implode(", ", $escaped_values) . ");\n");
        }
    }
    fwrite($handle, "\n");
}

fwrite($handle, "SET FOREIGN_KEY_CHECKS = 1;\n");
fwrite($handle, "-- ===================== End of Backup =====================\n");
fclose($handle);

$file_size = filesize($filepath);

// Record in backup_logs table
$log_sql = "INSERT INTO backup_logs (filename, file_size_bytes, record_count, created_by, created_at) 
            VALUES (?, ?, ?, ?, NOW())";
$log_stmt = mysqli_prepare($conn, $log_sql);
$created_by = (int)$user['user_id'];
mysqli_stmt_bind_param($log_stmt, "siii", $filename, $file_size, $total_records, $created_by);
mysqli_stmt_execute($log_stmt);
$backup_id = mysqli_insert_id($conn);
mysqli_stmt_close($log_stmt);

// Record in system_logs
log_activity($conn, 'BACKUP', 'DATABASE', (string)$backup_id, "Generated database backup {$filename} ({$file_size} bytes, {$total_records} records)");

set_flash_message('success', "Database backup created successfully: {$filename} (" . number_format($file_size) . " bytes).");
redirect(APP_URL . '/admin/backup/index.php');
